"""Verification tests for motion_energy, smart_reframe, beat_drop_mapper, kinetic_ramper.

Run: .venv-om/bin/python -m pytest openmontage/tests/ -q
Requires the synthetic sample media (generated by samples/generate_samples.py).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), "openmontage"))

from tools import make_tool
import pytest

SAMPLES = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "samples", "samples")


def _athlete():
    p = os.path.join(SAMPLES, "athlete_16x9.mp4")
    assert os.path.exists(p), "run samples/generate_samples.py first"
    return p


def _beat():
    p = os.path.join(SAMPLES, "beat_120bpm.wav")
    assert os.path.exists(p), "run samples/generate_samples.py first"
    return p


def test_motion_energy_detects_peaks(sample_athlete_clip):
    r = make_tool("motion_energy", input_path=sample_athlete_clip, method="diff")
    assert r.ok, r.error
    assert len(r.data["peaks"]) >= 1, "expected at least one highlight moment"
    assert r.data["summary"]["max_energy"] > 0


def test_smart_reframe_renders_and_low_jitter(sample_athlete_clip, tmp_path):
    import json, math
    boxes = []
    for i in range(int(30 * 6)):
        t = i / 30.0
        cx = 1280 * (0.5 + 0.10 * math.sin(2 * math.pi * 0.13 * t))
        cy = 720 * (0.5 + 0.32 * math.sin(2 * math.pi * 0.25 * t))
        boxes.append({"frame": i, "x": cx - 80, "y": cy - 130, "w": 160, "h": 260})
    bj = tmp_path / "boxes.json"
    bj.write_text(json.dumps(boxes))
    out = tmp_path / "reframed.mp4"
    r = make_tool("smart_reframe", input_path=sample_athlete_clip, out_path=str(out),
                  boxes_json=str(bj), target_w=540, alpha=0.25, deadband=6)
    assert r.ok, r.error
    assert out.exists()
    # dead-band should keep jitter modest (box moves ~tens of px/frame; with deadband 6
    # and EMA the post-smooth jitter mean should be < raw movement)
    assert r.metrics["jitter_px"] < 60


def test_beat_drop_mapper_bpm(sample_beat_audio):
    r = make_tool("beat_drop_mapper", audio_path=sample_beat_audio)
    assert r.ok, r.error
    bpm = r.data["summary"]["bpm"]
    assert abs(bpm - 120) < 8, f"BPM {bpm} not within 8 of truth 120"
    assert r.data["summary"]["beats"] >= 1


def test_kinetic_ramper_renders(sample_athlete_clip, sample_beat_audio, tmp_path):
    beats = tmp_path / "beats.json"
    rb = make_tool("beat_drop_mapper", audio_path=sample_beat_audio, out_json=str(beats))
    assert rb.ok
    out = tmp_path / "ramped.mp4"
    r = make_tool("kinetic_ramper", input_path=sample_athlete_clip, out_path=str(out),
                  map_json=str(beats), setup_speed=1.6, peak_speed=0.4)
    assert r.ok, r.error
    assert out.exists()
    assert r.metrics["segments"] >= 1
